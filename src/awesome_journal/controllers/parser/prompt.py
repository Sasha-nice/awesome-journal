def format_user_prompt(text: str, context: ParserContext, now_iso: str) -> str:
    """Формирует user-prompt для LLM.

    Структура output:
        Текущее время: {now_iso}

        Известные факты:
        [...]

        Известные измерения:
        [...]

        Категории задач:
        [...]

        Сообщение пользователя:
        {text}

    Списки рендерятся как JSON-массивы. Пустой список → "[]".
    """
    fact_names_json = json.dumps(
        [h.model_dump() for h in context.fact_names], ensure_ascii=False
    )
    measurement_names_json = json.dumps(
        [h.model_dump() for h in context.measurement_names], ensure_ascii=False
    )
    task_categories_json = json.dumps(
        [h.model_dump() for h in context.task_categories], ensure_ascii=False
    )

    return (
        f"Текущее время: {now_iso}\n\n"
        f"Известные факты:\n{fact_names_json}\n\n"
        f"Известные измерения:\n{measurement_names_json}\n\n"
        f"Категории задач:\n{task_categories_json}\n\n"
        f"Сообщение пользователя:\n{text}"
    )
